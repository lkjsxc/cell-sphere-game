#!/usr/bin/env node
/** Generate the checked-in title lifecycle from production simulation authority. */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { RunController } from '../src/simulation/simulator.js';
import { REPLAY_VERSION } from '../src/simulation/replay.js';
import { quantizeFrame, FRAME_FLAGS } from '../src/history/recorder.js';
import { encodeVisualHistory } from '../src/history/codec.js';

const ROOT = resolve(import.meta.dirname, '..'); const OUTPUT = resolve(ROOT, 'src/showcase/data.js');
const SEED = 20260701; const FRAME_MS = 750; const LAST_FRAME_MS = 21_750;
const DURATION_MS = 22_500; const FRAME_COUNT = LAST_FRAME_MS / FRAME_MS + 1;
const sourceHash = hashSources(); const probe = simulate();
const pressureTick = Math.max(probe.peakTick + 2, Math.round(probe.terminalTick * .62));
const matureTick = Math.max(probe.peakTick + 1, Math.min(pressureTick - 1,
  Math.round((probe.peakTick + pressureTick) / 2)));
const sourceTicks = Array.from({ length: FRAME_COUNT }, (_, index) => sourceTick(index * FRAME_MS));
sourceTicks[Math.round(6_500 / FRAME_MS)] = probe.peakTick;
const captures = captureTicks([...new Set(sourceTicks)].sort((a, b) => a - b));
const frames = sourceTicks.map((tick, index) => {
  const frame = captures.get(tick); return { ...frame, tick: index,
    flags: index === 0 ? FRAME_FLAGS.INITIAL | FRAME_FLAGS.MAJOR
      : index === FRAME_COUNT - 1 ? FRAME_FLAGS.TERMINAL | FRAME_FLAGS.MAJOR : 0 };
});
const buffer = encodeVisualHistory({ cellCount: probe.state.topo.nodeCount, seed: SEED,
  cadence: FRAME_MS }, frames);
const dataHash = sha(Buffer.from(buffer)); const base64 = Buffer.from(buffer).toString('base64');
const metadata = { schema: 2, seed: SEED, replayVersion: REPLAY_VERSION, sourceHash,
  dataHash, cellCount: probe.state.topo.nodeCount, frameIntervalMs: FRAME_MS,
  frameCount: FRAME_COUNT, durationMs: DURATION_MS, sourceTerminalTick: probe.terminalTick,
  peakLiving: probe.peakLiving, peakTick: probe.peakTick, matureTick,
  pressureTick, worldOrdinal: 3, collapseTick: probe.collapseTick,
  focusCell: probe.state.inoculationCell, reducedFrame: Math.round(8_000 / FRAME_MS) };
const content = `/** Generated by scripts/generate-title-showcase.mjs; do not hand-edit. */\nexport const TITLE_SHOWCASE = Object.freeze(${JSON.stringify({ ...metadata, dataBase64: base64 })});\n`;
if (process.argv.includes('--check')) {
  const actual = readFileSync(OUTPUT, 'utf8');
  if (actual !== content) { console.error('title showcase is stale; run npm run showcase:generate'); process.exit(1); }
  console.log(`title showcase current — ${dataHash} · ${FRAME_COUNT} frames · ${buffer.byteLength} bytes`);
} else {
  writeFileSync(OUTPUT, content); console.log(`wrote ${relative(ROOT, OUTPUT)} — ${dataHash} · ${FRAME_COUNT} frames · ${buffer.byteLength} bytes`);
}

function sourceTick(ms) {
  if (ms <= 750) return 0;
  if (ms < 6500) return interpolate(1, probe.peakTick, (ms - 800) / 5700);
  if (ms < 10500) return interpolate(probe.peakTick, matureTick, (ms - 6500) / 4000);
  if (ms < 14500) return interpolate(matureTick, pressureTick, (ms - 10500) / 4000);
  if (ms < 21500) return interpolate(probe.collapseTick, probe.terminalTick, (ms - 14500) / 7000);
  return probe.terminalTick;
}
function interpolate(a, b, t) { return Math.round(a + (b - a) * Math.max(0, Math.min(1, t))); }
function simulate() {
  const run = new RunController({ seed: SEED, worldOrdinal: 3, worldPotential: 16000 }); run.start();
  let peakLiving = run.state.aliveCount; let peakTick = 0; const living = [run.state.aliveCount];
  while (run.state.status !== 'extinct') { run.advance(1); living[run.state.tick] = run.state.aliveCount;
    if (run.state.aliveCount > peakLiving) { peakLiving = run.state.aliveCount; peakTick = run.state.tick; } }
  let collapseTick = run.state.tick;
  while (collapseTick > peakTick && living[collapseTick] < peakLiving * .75) collapseTick--;
  return { state: run.state, peakLiving, peakTick, collapseTick, terminalTick: run.state.tick };
}
function captureTicks(ticks) {
  const run = new RunController({ seed: SEED, worldOrdinal: 3, worldPotential: 16000 }); run.start(); const captures = new Map();
  for (const tick of ticks) {
    if (tick > run.state.tick) run.advance(tick - run.state.tick);
    captures.set(tick, { entropyQ: Math.round(run.state.entropy * 255), aliveCount: run.state.aliveCount,
      ...quantizeFrame(run.state) });
  }
  return captures;
}
function hashSources() {
  const roots = ['core', 'game', 'history', 'simulation', 'world']; const files = [];
  for (const name of roots) walk(resolve(ROOT, 'src', name), files);
  const hash = createHash('sha256');
  for (const file of files.sort()) { hash.update(relative(ROOT, file)); hash.update('\0'); hash.update(readFileSync(file)); }
  return hash.digest('hex');
}
function walk(directory, files) { for (const entry of readdirSync(directory, { withFileTypes: true })) {
  const path = resolve(directory, entry.name); if (entry.isDirectory()) walk(path, files); else if (entry.name.endsWith('.js')) files.push(path);
} }
function sha(value) { return createHash('sha256').update(value).digest('hex'); }
